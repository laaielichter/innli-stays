/** Translate a Dutch source text, filling {0}, {1}… with the arguments. */
export function T(nl, ...args) {
  const text = LANG === 'en' ? (EN[nl] ?? nl) : nl;
  return text.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}

const ATTRS = ['placeholder', 'title', 'aria-label'];
const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'PRE', 'CODE']);

function tr(text) {
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(text);
  const en = m[2] ? EN[m[2]] : undefined;
  return en === undefined || /\{\d\}/.test(en) ? null : m[1] + en + m[3];
}

/** Text inside code, owner/guest text and form fields stays as it is. Attributes of a textarea are still translated. */
function skipped(node, forAttributes = false) {
  for (let el = node.nodeType === 1 ? node : node.parentElement; el; el = el.parentElement) {
    if (forAttributes && el === node && el.tagName === 'TEXTAREA') continue;
    if (SKIP.has(el.tagName) || el.hasAttribute?.('data-user-text')) return true;
  }
  return false;
}

function translateNode(node) {
  if (node.nodeType === 3) {
    if (skipped(node)) return;
    const out = tr(node.data);
    if (out !== null && out !== node.data) node.data = out;
    return;
  }
  if (node.nodeType !== 1 || skipped(node, true)) return;
  for (const a of ATTRS) {
    const v = node.getAttribute(a);
    if (v) {
      const out = tr(v);
      if (out !== null && out !== v) node.setAttribute(a, out);
    }
  }
  if (node.tagName !== 'TEXTAREA') for (const child of node.childNodes) translateNode(child);
}

/** In English, translate the page now and everything that is added later. */
export function startI18n() {
  document.documentElement.lang = LANG;
  if (LANG === 'nl') return;
  document.title = tr(document.title) ?? document.title;
  translateNode(document.body);
  new MutationObserver((mutations) => {
    for (const m of mutations) {
      if (m.type === 'characterData') translateNode(m.target);
      else if (m.type === 'attributes') translateNode(m.target);
      else m.addedNodes.forEach(translateNode);
    }
  }).observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
}
